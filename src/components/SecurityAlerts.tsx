import { useEffect, useState } from 'react';
import {
  Check,
  Download,
  ExternalLink,
  Loader2,
  RefreshCw,
  Search,
  ShieldCheck,
  Trash2,
} from 'lucide-react';
import type { KevFeedResponse, SecurityAlert } from '../types/security';
import { SeverityIndicator } from './SeverityIndicator';

interface SecurityAlertsProps {
  alerts: SecurityAlert[];
  onUpdateAlertStatus: (id: string, status: SecurityAlert['status']) => void;
  onDeleteAlert: (id: string) => void;
  onClearResolved: () => void;
}

export function SecurityAlerts({
  alerts,
  onUpdateAlertStatus,
  onDeleteAlert,
  onClearResolved,
}: SecurityAlertsProps) {
  const [feedTab, setFeedTab] = useState<'workspace' | 'kev'>('workspace');
  const [severityFilter, setSeverityFilter] = useState<'All' | SecurityAlert['severity']>('All');
  const [statusFilter, setStatusFilter] = useState<'All' | SecurityAlert['status']>('All');
  const [searchQuery, setSearchQuery] = useState('');

  const [kevFeed, setKevFeed] = useState<KevFeedResponse | null>(null);
  const [kevLoading, setKevLoading] = useState(false);
  const [kevError, setKevError] = useState<string | null>(null);
  const [ransomwareOnly, setRansomwareOnly] = useState(false);

  const fetchKev = async () => {
    setKevLoading(true);
    setKevError(null);
    try {
      const response = await fetch('/api/alerts/kev');
      const data = await response.json();
      if (!response.ok) {
        setKevError(data.error || 'Failed to load live CISA vulnerability alerts.');
        return;
      }
      setKevFeed(data as KevFeedResponse);
    } catch (err) {
      setKevError(err instanceof Error ? err.message : 'Network error loading CISA advisory feed.');
    } finally {
      setKevLoading(false);
    }
  };

  useEffect(() => {
    if (feedTab === 'kev' && !kevFeed && !kevLoading) {
      void fetchKev();
    }
  }, [feedTab]);

  const filteredAlerts = alerts.filter((a) => {
    if (severityFilter !== 'All' && a.severity !== severityFilter) return false;
    if (statusFilter !== 'All' && a.status !== statusFilter) return false;
    if (searchQuery.trim()) {
      const q = searchQuery.toLowerCase();
      return (
        a.title.toLowerCase().includes(q) ||
        a.description.toLowerCase().includes(q) ||
        a.target.toLowerCase().includes(q)
      );
    }
    return true;
  });

  const filteredKev = (kevFeed?.vulnerabilities || []).filter((entry) => {
    if (ransomwareOnly && entry.knownRansomwareCampaignUse !== 'Known') return false;
    if (searchQuery.trim()) {
      const q = searchQuery.toLowerCase();
      return (
        entry.cveID.toLowerCase().includes(q) ||
        entry.vendorProject.toLowerCase().includes(q) ||
        entry.product.toLowerCase().includes(q) ||
        entry.vulnerabilityName.toLowerCase().includes(q)
      );
    }
    return true;
  });

  const handleExportJson = () => {
    const blob = new Blob([JSON.stringify(alerts, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `aicybershield-alerts-${new Date().toISOString().slice(0, 10)}.json`;
    link.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="space-y-6">
      <section className="neon-panel rounded-2xl p-5 sm:p-6 space-y-5">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
          <div>
            <h1 className="text-xl sm:text-2xl font-bold text-slate-900 dark:text-slate-50">
              Security Alerts Center
            </h1>
            <p className="text-xs sm:text-sm text-slate-600 dark:text-slate-400 mt-1">
              Triage alerts generated by your scans alongside live CISA Known Exploited Vulnerabilities.
            </p>
          </div>

          <div className="inline-flex p-1 rounded-xl bg-slate-100 dark:bg-slate-950 border border-slate-200 dark:border-slate-800 self-start">
            <button
              type="button"
              onClick={() => setFeedTab('workspace')}
              className={`min-h-[38px] px-3.5 py-1.5 rounded-lg text-xs font-medium transition-colors cursor-pointer whitespace-nowrap ${
                feedTab === 'workspace'
                  ? 'bg-sky-600 text-white'
                  : 'text-slate-600 dark:text-slate-400 hover:text-slate-900 dark:hover:text-slate-200'
              }`}
            >
              Workspace Alerts ({alerts.filter((a) => a.status === 'Open').length})
            </button>
            <button
              type="button"
              onClick={() => setFeedTab('kev')}
              className={`min-h-[38px] px-3.5 py-1.5 rounded-lg text-xs font-medium transition-colors cursor-pointer whitespace-nowrap ${
                feedTab === 'kev'
                  ? 'bg-sky-600 text-white'
                  : 'text-slate-600 dark:text-slate-400 hover:text-slate-900 dark:hover:text-slate-200'
              }`}
            >
              CISA Exploited CVEs
            </button>
          </div>
        </div>

        {/* Search & Filter Controls */}
        <div className="flex flex-col md:flex-row md:items-center justify-between gap-3">
          <div className="relative flex-1 max-w-md">
            <Search className="w-4 h-4 text-slate-500 dark:text-slate-400 absolute left-3.5 top-1/2 -translate-y-1/2" aria-hidden="true" />
            <input
              type="text"
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              placeholder={
                feedTab === 'workspace' ? 'Search alerts, domains, targets...' : 'Search CVE ID, vendor, or product...'
              }
              aria-label="Filter security alerts"
              className="w-full min-h-[42px] pl-10 pr-4 py-2 rounded-xl bg-slate-50 dark:bg-slate-950/90 border border-slate-300 dark:border-slate-800 text-xs sm:text-sm text-slate-900 dark:text-slate-100 placeholder:text-slate-500 focus:outline-none focus:border-sky-500 dark:focus:border-sky-400"
            />
          </div>

          {feedTab === 'workspace' ? (
            <div className="flex flex-wrap items-center gap-2">
              <select
                value={severityFilter}
                onChange={(e) => setSeverityFilter(e.target.value as 'All' | SecurityAlert['severity'])}
                aria-label="Filter by severity"
                className="min-h-[40px] px-3 py-1.5 rounded-xl bg-slate-50 dark:bg-slate-950 border border-slate-300 dark:border-slate-800 text-xs text-slate-800 dark:text-slate-200 focus:outline-none focus:border-sky-500 dark:focus:border-sky-400"
              >
                <option value="All">All Severities</option>
                <option value="Critical">Critical</option>
                <option value="High">High</option>
                <option value="Medium">Medium</option>
                <option value="Low">Low</option>
              </select>

              <select
                value={statusFilter}
                onChange={(e) => setStatusFilter(e.target.value as 'All' | SecurityAlert['status'])}
                aria-label="Filter by status"
                className="min-h-[40px] px-3 py-1.5 rounded-xl bg-slate-50 dark:bg-slate-950 border border-slate-300 dark:border-slate-800 text-xs text-slate-800 dark:text-slate-200 focus:outline-none focus:border-sky-500 dark:focus:border-sky-400"
              >
                <option value="All">All Statuses</option>
                <option value="Open">Open</option>
                <option value="Acknowledged">Acknowledged</option>
                <option value="Resolved">Resolved</option>
              </select>

              {alerts.length > 0 && (
                <>
                  <button
                    type="button"
                    onClick={handleExportJson}
                    className="min-h-[40px] px-3 py-1.5 rounded-xl bg-slate-100 dark:bg-slate-900 hover:bg-slate-200 dark:hover:bg-slate-800 border border-slate-200 dark:border-slate-800 text-xs text-slate-700 dark:text-slate-200 inline-flex items-center gap-1.5 cursor-pointer"
                  >
                    <Download className="w-3.5 h-3.5" aria-hidden="true" />
                    <span>Export</span>
                  </button>
                  <button
                    type="button"
                    onClick={onClearResolved}
                    className="min-h-[40px] px-3 py-1.5 rounded-xl bg-slate-100 dark:bg-slate-900 hover:bg-slate-200 dark:hover:bg-slate-800 border border-slate-200 dark:border-slate-800 text-xs text-slate-700 dark:text-slate-300 cursor-pointer"
                  >
                    Clear Resolved
                  </button>
                </>
              )}
            </div>
          ) : (
            <div className="flex flex-wrap items-center gap-3">
              <label className="inline-flex items-center gap-2 text-xs text-slate-700 dark:text-slate-300 cursor-pointer min-h-[40px]">
                <input
                  type="checkbox"
                  checked={ransomwareOnly}
                  onChange={(e) => setRansomwareOnly(e.target.checked)}
                  className="w-4 h-4 rounded accent-sky-500"
                />
                <span>Known Ransomware Only</span>
              </label>
              <button
                type="button"
                onClick={() => void fetchKev()}
                disabled={kevLoading}
                className="min-h-[40px] px-3.5 py-1.5 rounded-xl bg-slate-100 dark:bg-slate-900 hover:bg-slate-200 dark:hover:bg-slate-800 border border-slate-200 dark:border-slate-800 text-xs text-sky-700 dark:text-sky-300 inline-flex items-center gap-1.5 cursor-pointer disabled:opacity-50"
              >
                <RefreshCw className={`w-3.5 h-3.5 ${kevLoading ? 'animate-spin' : ''}`} aria-hidden="true" />
                <span>Refresh Feed</span>
              </button>
            </div>
          )}
        </div>

        {/* Tab 1: Workspace Alerts */}
        {feedTab === 'workspace' && (
          <div>
            {filteredAlerts.length === 0 ? (
              <div className="py-12 text-center border border-dashed border-slate-300 dark:border-slate-800 rounded-xl px-4">
                <ShieldCheck className="w-9 h-9 text-emerald-600 dark:text-emerald-400 mx-auto mb-2.5" aria-hidden="true" />
                <p className="text-sm font-semibold text-slate-800 dark:text-slate-200">
                  {alerts.length === 0 ? 'No Security Alerts Recorded' : 'No Alerts Match Your Filters'}
                </p>
                <p className="text-xs text-slate-500 dark:text-slate-400 mt-1 max-w-md mx-auto">
                  {alerts.length === 0
                    ? 'When you detect a suspicious/malicious URL, an exposed password, or a high-severity threat artifact, an actionable alert will appear here.'
                    : 'Adjust your severity, status, or search filters to view other alerts.'}
                </p>
              </div>
            ) : (
              <div className="divide-y divide-slate-200 dark:divide-slate-800/80">
                {filteredAlerts.map((alert) => (
                  <article key={alert.id} className="py-4 flex flex-col lg:flex-row lg:items-center justify-between gap-4">
                    <div className="min-w-0 space-y-1">
                      <div className="flex flex-wrap items-center gap-2 text-xs text-slate-500 dark:text-slate-400">
                        <SeverityIndicator level={alert.severity} />
                        <span aria-hidden="true">·</span>
                        <span>{alert.source}</span>
                        <span aria-hidden="true">·</span>
                        <span
                          className={
                            alert.status === 'Resolved'
                              ? 'text-emerald-600 dark:text-emerald-400 font-medium'
                              : alert.status === 'Acknowledged'
                                ? 'text-sky-600 dark:text-sky-400 font-medium'
                                : 'text-amber-600 dark:text-amber-400 font-medium'
                          }
                        >
                          {alert.status}
                        </span>
                        <span aria-hidden="true">·</span>
                        <span className="font-mono tabular-nums">
                          {new Date(alert.createdAt).toLocaleString([], {
                            month: 'short',
                            day: 'numeric',
                            hour: '2-digit',
                            minute: '2-digit',
                          })}
                        </span>
                      </div>

                      <h3 className="text-sm sm:text-base font-semibold text-slate-900 dark:text-slate-100">
                        {alert.title}
                      </h3>
                      <p className="text-xs sm:text-sm text-slate-700 dark:text-slate-300">{alert.description}</p>
                      <p className="text-xs font-mono text-slate-500 dark:text-slate-400 break-all">
                        Target: {alert.target}
                      </p>
                    </div>

                    <div className="flex flex-wrap items-center gap-2 shrink-0">
                      {alert.status === 'Open' && (
                        <button
                          type="button"
                          onClick={() => onUpdateAlertStatus(alert.id, 'Acknowledged')}
                          className="min-h-[40px] px-3.5 py-1.5 rounded-lg bg-slate-100 dark:bg-slate-900 hover:bg-slate-200 dark:hover:bg-slate-800 border border-slate-300 dark:border-slate-700 text-xs font-medium text-slate-800 dark:text-slate-200 cursor-pointer"
                        >
                          Acknowledge
                        </button>
                      )}
                      {alert.status !== 'Resolved' ? (
                        <button
                          type="button"
                          onClick={() => onUpdateAlertStatus(alert.id, 'Resolved')}
                          className="min-h-[40px] px-3.5 py-1.5 rounded-lg bg-sky-600 hover:bg-sky-500 text-xs font-semibold text-white inline-flex items-center gap-1.5 cursor-pointer"
                        >
                          <Check className="w-3.5 h-3.5" aria-hidden="true" />
                          <span>Resolve</span>
                        </button>
                      ) : (
                        <button
                          type="button"
                          onClick={() => onUpdateAlertStatus(alert.id, 'Open')}
                          className="min-h-[40px] px-3.5 py-1.5 rounded-lg bg-slate-100 dark:bg-slate-900 hover:bg-slate-200 dark:hover:bg-slate-800 border border-slate-300 dark:border-slate-700 text-xs font-medium text-slate-700 dark:text-slate-300 cursor-pointer"
                        >
                          Reopen
                        </button>
                      )}
                      <button
                        type="button"
                        onClick={() => onDeleteAlert(alert.id)}
                        aria-label="Delete alert"
                        className="min-h-[40px] min-w-[40px] flex items-center justify-center rounded-lg bg-slate-100 dark:bg-slate-950 hover:bg-rose-50 dark:hover:bg-rose-950/50 border border-slate-200 dark:border-slate-800 text-slate-500 dark:text-slate-400 hover:text-rose-600 dark:hover:text-rose-400 cursor-pointer"
                      >
                        <Trash2 className="w-4 h-4" aria-hidden="true" />
                      </button>
                    </div>
                  </article>
                ))}
              </div>
            )}
          </div>
        )}

        {/* Tab 2: Live CISA KEV Feed */}
        {feedTab === 'kev' && (
          <div className="space-y-4">
            {kevFeed && (
              <p className="text-xs text-slate-600 dark:text-slate-400 tabular-nums">
                CISA Catalog {kevFeed.catalogVersion} · {kevFeed.totalCount.toLocaleString()} total known exploited vulnerabilities · Showing latest {filteredKev.length}
              </p>
            )}

            {kevLoading && (
              <div className="py-12 flex items-center justify-center gap-3 text-sm text-slate-700 dark:text-slate-300">
                <Loader2 className="w-5 h-5 text-sky-600 dark:text-sky-400 animate-spin" aria-hidden="true" />
                <span>Fetching live CISA Known Exploited Vulnerabilities...</span>
              </div>
            )}

            {kevError && (
              <div
                role="alert"
                className="p-4 rounded-xl bg-rose-50 dark:bg-rose-950/40 border border-rose-200 dark:border-rose-500/35 text-xs sm:text-sm text-rose-800 dark:text-rose-200 flex items-center justify-between gap-4"
              >
                <span>{kevError}</span>
                <button
                  type="button"
                  onClick={() => void fetchKev()}
                  className="min-h-[36px] px-3 py-1.5 rounded-lg bg-rose-600 hover:bg-rose-500 text-xs font-medium text-white shrink-0 cursor-pointer"
                >
                  Retry
                </button>
              </div>
            )}

            {!kevLoading && !kevError && filteredKev.length > 0 && (
              <div className="divide-y divide-slate-200 dark:divide-slate-800/80">
                {filteredKev.map((entry) => (
                  <article key={entry.cveID} className="py-4 space-y-1.5">
                    <div className="flex flex-wrap items-center justify-between gap-2">
                      <div className="flex flex-wrap items-center gap-2 text-xs text-slate-500 dark:text-slate-400">
                        <span className="font-mono font-semibold text-sky-700 dark:text-sky-400">{entry.cveID}</span>
                        <span aria-hidden="true">·</span>
                        <span>{entry.vendorProject} {entry.product}</span>
                        <span aria-hidden="true">·</span>
                        <span className="font-mono tabular-nums">Added {entry.dateAdded}</span>
                        {entry.knownRansomwareCampaignUse === 'Known' && (
                          <>
                            <span aria-hidden="true">·</span>
                            <span className="text-rose-600 dark:text-rose-400 font-semibold">Ransomware Campaign</span>
                          </>
                        )}
                      </div>

                      <a
                        href={`https://nvd.nist.gov/vuln/detail/${entry.cveID}`}
                        target="_blank"
                        rel="noopener noreferrer"
                        className="inline-flex items-center gap-1 text-xs font-medium text-sky-700 dark:text-sky-400 hover:underline whitespace-nowrap"
                      >
                        <span>NVD Details</span>
                        <ExternalLink className="w-3 h-3" aria-hidden="true" />
                      </a>
                    </div>

                    <h3 className="text-sm font-semibold text-slate-900 dark:text-slate-100">
                      {entry.vulnerabilityName}
                    </h3>
                    <p className="text-xs sm:text-sm text-slate-700 dark:text-slate-300 leading-relaxed">
                      {entry.shortDescription}
                    </p>
                    <p className="text-xs text-slate-600 dark:text-slate-400">
                      <strong className="text-slate-800 dark:text-slate-300">Required Action:</strong>{' '}
                      {entry.requiredAction} (Due {entry.dueDate})
                    </p>
                  </article>
                ))}
              </div>
            )}
          </div>
        )}
      </section>
    </div>
  );
}
